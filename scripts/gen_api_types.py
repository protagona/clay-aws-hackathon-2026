"""Generate web/src/types.ts from the API's Pydantic models (src/foundry/api/schemas.py), increment 17.

    uv run python scripts/gen_api_types.py           # rewrite web/src/types.ts
    uv run python scripts/gen_api_types.py --check   # exit 1 if it is stale

The models of every /api route (responses in serialization mode, request bodies in validation mode) go through
Pydantic's JSON Schema, and each schema becomes one exported TypeScript interface of the same name. Only the JSON
Schema constructs our models use are supported; anything else raises, so nothing is emitted silently wrong.
`ApiRoutes` maps "METHOD /api/path" to its response type (tests/test_api_contract.py checks call sites against it).
"""

from __future__ import annotations

import json
import re
import sys
import tempfile
from pathlib import Path

from pydantic.json_schema import models_json_schema

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "src" / "types.ts"
HEADER = ("// GENERATED by scripts/gen_api_types.py from src/foundry/api/schemas.py: do not edit.\n"
          "// After changing a model, run: uv run python scripts/gen_api_types.py\n")


def api_routes() -> list[tuple[str, str, type | None, type | None]]:
    """(method, path, response model, body model) for every /api route, in matching order. Read from the router
    factory server.py includes (FastAPI 0.16x keeps an included router as one opaque entry in app.routes)."""
    from fastapi.routing import APIRoute

    from foundry.api.routes import make_router
    from foundry.services.workspace import Workspace

    with tempfile.TemporaryDirectory() as tmp:
        # access=object(): include the sign-in routes a deployment with auth serves (aws-deploy ADR-9)
        router = make_router(Workspace(Path(tmp), ROOT, 8765), "token", access=object())
    out = []
    for r in router.routes:
        if not isinstance(r, APIRoute) or not r.path.startswith("/api/"):
            continue
        body = r.body_field.field_info.annotation if r.body_field is not None else None
        # Only our declared bodies: FastAPI generates a model for each multipart form (File/Form), which isn't
        # part of the JSON contract the web app types.
        body = body if isinstance(body, type) and getattr(body, "__module__", "") == "foundry.api.schemas" else None
        for method in sorted(r.methods):
            out.append((method, r.path, r.response_model, body))
    return out


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s:
        parts = [ts_type(x) for x in s["anyOf"]]
        return " | ".join(f"({p})" if " | " in p and not p.endswith("null") else p for p in parts)
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x) for x in s["prefixItems"]) + "]"
        item = ts_type(s.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if t == "object":
        if "properties" in s:
            raise ValueError(f"inline object schemas aren't supported; make it a model: {s}")
        extra = s.get("additionalProperties", True)
        return "Record<string, unknown>" if extra is True else f"Record<string, {ts_type(extra)}>"
    if not s or set(s) <= {"title", "description", "default"}:
        return "unknown"
    raise ValueError(f"unsupported JSON Schema construct: {s}")


def interface(name: str, s: dict) -> str:
    if s.get("type") != "object" or "properties" not in s:
        raise ValueError(f"{name}: a model must be an object schema")
    req = set(s.get("required", []))
    lines = []
    if s.get("description"):
        lines.append("/** " + " ".join(s["description"].split()) + " */")
    lines.append(f"export interface {name} {{")
    for key, prop in s["properties"].items():
        k = key if re.fullmatch(r"[A-Za-z_$][\w$]*", key) else json.dumps(key)
        lines.append(f"  {k}{'' if key in req else '?'}: {ts_type(prop)};")
    if s.get("additionalProperties") is True:
        lines.append("  [key: string]: unknown;")
    elif s.get("additionalProperties") not in (False, None):
        raise ValueError(f"{name}: typed additionalProperties on a model isn't supported")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    from foundry.api import schemas

    routes = api_routes()
    responses = {m for _, _, m, _ in routes if m is not None}
    bodies = {b for _, _, _, b in routes if b is not None}
    clash = {m.__name__ for m in responses & bodies}
    if clash:
        raise ValueError(f"used as both a response and a request body: {clash}")
    inputs = [(m, "serialization") for m in sorted(responses, key=lambda m: m.__name__)]
    inputs += [(b, "validation") for b in sorted(bodies, key=lambda b: b.__name__)]
    _, top = models_json_schema(inputs, ref_template="#/$defs/{model}")
    defs = top.get("$defs", {})
    names = [d for d in defs if not re.fullmatch(r"[A-Za-z_]\w*", d) or "__" in d]
    if names:
        raise ValueError(f"schema names that aren't TypeScript identifiers (a name clash between modes?): {names}")
    parts = [HEADER]
    column = " | ".join(json.dumps(v) for v in schemas.Column.__args__)
    parts.append(f"export type Column = {column};")
    parts += [interface(n, defs[n]) for n in sorted(defs)]
    lines = ["/** Every /api route and the type it returns (checked against web call sites by tests). */",
             "export interface ApiRoutes {"]
    for method, path, model, _ in sorted(routes, key=lambda r: (r[1], r[0])):
        if model is not None:
            lines.append(f"  {json.dumps(f'{method} {path}')}: {model.__name__};")
    lines.append("}")
    parts.append("\n".join(lines))
    return "\n\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run: uv run python scripts/gen_api_types.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
